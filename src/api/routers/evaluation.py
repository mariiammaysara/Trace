"""GET /evaluation -- Phase 17's Model Evaluation dashboard reads real,
already-measured detection/tracking results, not numbers duplicated (and
liable to drift) in frontend code.

This route does no evaluation itself and recomputes nothing: it reads
Phase 14's own checked-in evaluation-harness output
(`evaluation/results/detection_comparison.json`,
`evaluation/results/tracking_comparison.json` -- see Section 15/19 of
TRACE_STUDY_GUIDE.md) straight off disk and returns it close to verbatim.
Those two files are the single source of truth; if they're regenerated by
re-running `evaluation/detection/evaluate.py` / `evaluation/tracking/
evaluate.py`, this endpoint picks up the new numbers with no code change.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

router = APIRouter(tags=["evaluation"])

# Relative to the process's working directory -- the same convention already
# used for configs/cameras/ (src/geometry/homography.py, line_crossing.py,
# zone.py's configs_dir="configs/cameras" default), not a __file__-relative
# walk up from this module's own location. That distinction matters here:
# evaluation/detection/evaluate.py's REPO_ROOT = Path(__file__)...parent
# convention is only valid for a script always run loose from a source
# checkout; this module ships inside the `api` package that gets `pip
# install`ed (Dockerfile), so __file__ resolves to its site-packages install
# location at runtime, not this repo -- Path(__file__).resolve().parent * 4
# landed at /usr/local/lib/python3.11/ inside the container, not /app, which
# is why /evaluation 503'd there even with evaluation/results/ copied into
# the image. uvicorn (Dockerfile CMD) and every documented local dev command
# already run with the repo root as CWD, same as configs/cameras/ relies on.
DETECTION_RESULTS_PATH = Path("evaluation/results/detection_comparison.json")
TRACKING_RESULTS_PATH = Path("evaluation/results/tracking_comparison.json")


class EvaluationResponse(BaseModel):
    """Deliberately close to a raw passthrough of the two result files
    (`Dict[str, Any]` for their nested per-class/per-model bodies) rather
    than a re-typed, re-shaped model: the point of this endpoint is that the
    numbers it returns are exactly the numbers in the checked-in evaluation
    artifact, not a hand-maintained parallel representation of them."""

    detection: Dict[str, Any]
    tracking: Dict[str, Any]


def _read_json(path: Path) -> Dict[str, Any]:
    if not path.exists():
        raise HTTPException(
            status_code=503,
            detail=(
                f"evaluation results not found at {path} -- run the Phase 14 evaluation "
                "harness first (evaluation/detection/evaluate.py, evaluation/tracking/evaluate.py)"
            ),
        )
    with path.open(encoding="utf-8") as f:
        return json.load(f)


@router.get("/evaluation", response_model=EvaluationResponse)
def get_evaluation() -> EvaluationResponse:
    return EvaluationResponse(
        detection=_read_json(DETECTION_RESULTS_PATH),
        tracking=_read_json(TRACKING_RESULTS_PATH),
    )
